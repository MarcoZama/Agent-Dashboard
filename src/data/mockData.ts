type CapabilityOverrides = Partial<Agent['capabilities']> & {
  mcp?: boolean
  aiBuilderPrompts?: boolean
  skills?: boolean
}

const cap = (overrides: CapabilityOverrides = {}): Agent['capabilities'] => ({
  connectedAgents: overrides.connectedAgents ?? overrides.skills ?? false,
  webSearch: overrides.webSearch ?? false,
  connectors:
    overrides.connectors ??
    overrides.mcp ??
    overrides.aiBuilderPrompts ??
    overrides.toolsActions ??
    false,
  generativeAI: overrides.generativeAI ?? false,
  toolsActions: overrides.toolsActions ?? false,
  knowledgeSources: overrides.knowledgeSources ?? false,
  deepReasoning: overrides.deepReasoning ?? false,
})

interface AgentSeed {
  id: string
  name: string
  product: Agent['product']
  environmentId: string
  environmentName: string
  type: Agent['type']
  owner: string
  ownerEmail?: string
  auth: Agent['auth']
  published: boolean
  createdOn: string
  healthScore: number
  llmModel: string
  channels: Agent['channels']
  capabilities: Agent['capabilities']
  autonomous: boolean
  credits?: number
  conversations?: number
  messages?: number
  activeUsers?: number
  lastUsedOn?: string
}

const withCost = (a: AgentSeed): Agent => {
  const env = ENV_BY_ID.get(a.environmentId)
  const ownerEmail = OWNERS[a.owner] ?? a.ownerEmail
  const le = deriveLegalEntity(ownerEmail)
  return {
    id: a.id,
    agentId: a.id,
    name: a.name,
    product: a.product,
    environmentId: a.environmentId,
    environmentName: a.environmentName,
    type: a.type,
    owner: a.owner,
    ownerEmail,
    legalEntity: le.domain,
    legalEntityLabel: le.label,
    environmentType: (env?.type ?? 'Production') as EnvironmentType,
    environmentUrl: env?.url,
    auth: a.auth,
    published: a.published,
    createdIn: a.product === 'm365' ? 'Microsoft 365 Copilot Agent Builder' : 'Copilot Studio',
    schemaName: `sample_${a.id.replace(/[^a-z0-9]/gi, '')}`,
    harness: a.capabilities.deepReasoning ? 'GitHub Copilot' : 'Standard',
    orchestration: a.capabilities.generativeAI ? 'Generative' : 'Classic',
    isQuarantined: false,
    isManaged: a.product === 'powerPlatform',
    sharedWithEntireTenant: false,
    viewerUserCount: 0,
    viewerGroupCount: 0,
    editorUserCount: 1,
    editorGroupCount: 0,
    toolsCount: a.capabilities.toolsActions ? 2 : 0,
    knowledgeSourcesCount: a.capabilities.knowledgeSources ? 3 : 0,
    connectedAgentsCount: a.capabilities.connectedAgents ? 1 : 0,
    topicsCount: 4,
    connectorCount: a.capabilities.connectors ? 2 : 0,
    connectorOperationCount: a.capabilities.connectors ? 3 : 0,
    triggersCount: a.autonomous ? 1 : 0,
    webSearchEnabled: a.capabilities.webSearch,
    createdOn: a.createdOn,
    healthScore: a.healthScore,
    llmModel: a.llmModel,
    channels: a.channels,
    capabilities: a.capabilities,
    autonomous: a.autonomous,
  }
}

